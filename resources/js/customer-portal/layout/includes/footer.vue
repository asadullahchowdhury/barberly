            formData: {
                language: 'English',
            },
            languages: [],
            showButton: false,
        }
    },
    mounted() {
        this.languageList()
        window.addEventListener('scroll', this.handleScroll)
    },

    destroyed() {
        window.removeEventListener('scroll', this.handleScroll)
    },

    methods: {

        /* Function to open payment modal */
        openLanguageModal() {
            let modal = new bootstrap.Modal(document.getElementById('languageModal'))
            modal.show();
        },

        /* Function of language list from json file */
        languageList() {
            this.languages = window.core.languages;
        },

        /* Function to close payment modal */
        closeLanguageModal() {
            const Modal = document.querySelector('#languageModal');
            const Instance = bootstrap.Modal.getInstance(Modal);
            Instance.hide();
        },

        /* Function to scroll to top */
        scrollToTop() {
            window.scrollTo({
                top: 0,
                behavior: 'smooth',
            })
        },

        /* Function to scroll visible or hide */
        handleScroll() {
            const scrollPosition = window.scrollY;
            const windowHeight = window.innerHeight;
            if (scrollPosition > 0 && scrollPosition > windowHeight * 0.5) {
                this.showButton = true;
            } else {
                this.showButton = false;
            }
        },

    }
}

